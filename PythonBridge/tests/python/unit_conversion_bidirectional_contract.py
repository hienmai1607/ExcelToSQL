"""Rollback-only contracts for linked reciprocal conversions."""
import base64
import re
import unittest
from uuid import uuid4
from decimal import Decimal as D
from fastapi import HTTPException
from raw_material_sql_contract import SQLContracts, ROOT
import unit_conversion_api as api


class Bidirectional(SQLContracts):
    def setUp(self):
        super().setUp()
        for filename in ('39_unit_conversion.sql', '40_unit_conversion_precision.sql'):
            for sql in re.split(r'^GO\s*$', (ROOT / 'sql' / filename).read_text(), flags=re.M | re.I):
                if sql.strip():
                    self.cur.execute(sql)
                    while self.cur.nextset(): pass
        self.codes = ['BI-' + uuid4().hex[:10] for _ in range(2)]
        self.units = [self.cur.execute('INSERT dbo.UoM(UoMCode,CreatedBy) VALUES(?,?);SELECT CONVERT(INT,SCOPE_IDENTITY())', code, self.ctx.user_id).fetchval() for code in self.codes]
        self.material = self.save('raw-materials', command='C', changes=dict(MaterialName='Bidirectional test', UnitOfMeasure=self.codes[1]))['NewID']
        if (ROOT / 'sql/64_unit_conversion_bidirectional.sql').exists():
            self.migrate()
            self.migrate()

    def migrate(self):
        for sql in re.split(r'^GO\s*$', (ROOT / 'sql/64_unit_conversion_bidirectional.sql').read_text(), flags=re.M | re.I):
            if sql.strip():
                self.cur.execute(sql)
                while self.cur.nextset(): pass

    def save_pair(self, factor='0.265', **values):
        return api.save(api.Conversion(FromUoMID=self.units[0], ToUoMID=self.units[1],
            Factor=D(factor), RawMaterialID=self.material, **values), self.ctx)

    def row(self, identifier):
        self.cur.execute('SELECT * FROM dbo.UnitConversion WHERE ID=?', identifier)
        return dict(zip([d[0] for d in self.cur.description], self.cur.fetchone()))

    def edit(self, row, **changes):
        values = {k: row[k] for k in ('ID', 'FromUoMID', 'ToUoMID', 'Factor', 'PackagingMaterialID', 'RawMaterialID', 'VendorID', 'Status')}
        values['RowVersion'] = base64.b64encode(row['RowVersion']).decode()
        values.update(changes)
        return api.save(api.Conversion(**values), self.ctx)

    def test_saving_one_direction_creates_the_reciprocal(self):
        saved = self.save_pair()
        actual = self.cur.execute('SELECT Factor FROM dbo.fn_UnitConversion(?,?,NULL,?,NULL)',
            self.codes[1], self.codes[0], self.material).fetchval()
        self.assertEqual(actual, D('3.773584906'))
        source = self.row(saved['ID'])
        reverse = self.row(source['ReverseConversionID'])
        self.assertEqual(reverse['ReverseConversionID'], source['ID'])
        self.assertEqual(reverse['RawMaterialID'], self.material)
        self.assertTrue(reverse['IsAutoGenerated'])

    def test_edit_either_direction_updates_both_and_stales_the_other_version(self):
        source = self.row(self.save_pair()['ID'])
        reverse = self.row(source['ReverseConversionID'])
        self.edit(reverse, Factor='4')
        self.assertEqual(self.row(source['ID'])['Factor'], D('.25'))
        self.assertEqual(self.row(reverse['ID'])['Factor'], D('4'))
        with self.assertRaises(HTTPException) as error: self.edit(source, Factor='2')
        self.assertEqual(error.exception.status_code, 409)
        self.assertEqual(self.row(source['ID'])['Factor'], D('.25'))

    def test_blocking_and_reactivating_updates_both(self):
        source = self.row(self.save_pair()['ID'])
        self.edit(source, Status='Block')
        self.assertEqual(self.row(source['ID'])['Status'], 'Block')
        self.assertEqual(self.row(source['ReverseConversionID'])['Status'], 'Block')
        self.edit(self.row(source['ReverseConversionID']), Status='Active')
        self.assertEqual(self.row(source['ID'])['Status'], 'Active')

    def test_vendor_scope_and_general_fallback_are_not_crossed(self):
        api.save(api.Conversion(FromUoMID=self.units[0], ToUoMID=self.units[1], Factor=1000), self.ctx)
        vendor = self.cur.execute('INSERT dbo.Vendor(VendorName,CreatedBy) VALUES(?,?);SELECT CONVERT(INT,SCOPE_IDENTITY())', self.codes[0], self.ctx.user_id).fetchval()
        source = self.row(self.save_pair('2', VendorID=vendor)['ID'])
        self.assertEqual(self.row(source['ReverseConversionID'])['VendorID'], vendor)
        self.assertEqual(self.cur.execute('SELECT Factor FROM dbo.fn_UnitConversion(?,?,NULL,?,?)', self.codes[1], self.codes[0], self.material, vendor).fetchval(), D('.5'))
        self.assertEqual(self.cur.execute('SELECT Factor FROM dbo.fn_UnitConversion(?,?,NULL,?,NULL)', self.codes[1], self.codes[0], self.material).fetchval(), D('.001'))

    def test_status_only_edit_of_rounded_reverse_preserves_original_factor(self):
        source = self.row(self.save_pair('123.456789012')['ID'])
        reverse = self.row(source['ReverseConversionID'])
        self.edit(reverse, Status='Block')
        self.assertEqual(self.row(source['ID'])['Factor'], D('123.456789012'))
        self.edit(self.row(reverse['ID']), Status='Active')
        self.assertEqual(self.row(source['ID'])['Factor'], D('123.456789012'))

    def test_changing_units_moves_the_pair(self):
        source = self.row(self.save_pair()['ID'])
        third = self.cur.execute('INSERT dbo.UoM(UoMCode,CreatedBy) VALUES(?,?);SELECT CONVERT(INT,SCOPE_IDENTITY())', self.codes[0]+'-3', self.ctx.user_id).fetchval()
        self.edit(source, ToUoMID=third)
        reverse = self.row(source['ReverseConversionID'])
        self.assertEqual((reverse['FromUoMID'], reverse['ToUoMID']), (third, self.units[0]))
        self.assertIsNone(self.cur.execute('SELECT Factor FROM dbo.fn_UnitConversion(?,?,NULL,?,NULL)', self.codes[1], self.codes[0], self.material).fetchval())

    def test_conflicting_independent_reverse_is_not_overwritten(self):
        existing = self.cur.execute('INSERT dbo.UnitConversion(FromUoMID,ToUoMID,Factor,RawMaterialID,CreatedBy) VALUES(?,?,5,?,?);SELECT CONVERT(INT,SCOPE_IDENTITY())', self.units[1], self.units[0], self.material, self.ctx.user_id).fetchval()
        with self.assertRaises(HTTPException) as error: self.save_pair('2')
        self.assertEqual(error.exception.status_code, 422)
        self.assertEqual(self.row(existing)['Factor'], D('5'))
        self.assertEqual(self.cur.execute('SELECT COUNT(*) FROM dbo.UnitConversion WHERE RawMaterialID=?', self.material).fetchval(), 1)

    def test_matching_independent_reverse_is_linked(self):
        existing = self.cur.execute('INSERT dbo.UnitConversion(FromUoMID,ToUoMID,Factor,RawMaterialID,CreatedBy) VALUES(?,?,.5,?,?);SELECT CONVERT(INT,SCOPE_IDENTITY())', self.units[1], self.units[0], self.material, self.ctx.user_id).fetchval()
        source = self.row(self.save_pair('2')['ID'])
        self.assertEqual(source['ReverseConversionID'], existing)
        self.assertEqual(self.cur.execute('SELECT COUNT(*) FROM dbo.UnitConversion WHERE RawMaterialID=?', self.material).fetchval(), 2)

    def test_unrepresentable_reverse_is_rejected_atomically(self):
        with self.assertRaises(HTTPException) as error: self.save_pair('999999999999999')
        self.assertEqual(error.exception.status_code, 422)
        self.assertEqual(self.cur.execute('SELECT COUNT(*) FROM dbo.UnitConversion WHERE RawMaterialID=?', self.material).fetchval(), 0)

    def test_migration_backfills_missing_reverse_once(self):
        existing = self.cur.execute('INSERT dbo.UnitConversion(FromUoMID,ToUoMID,Factor,RawMaterialID,CreatedBy) VALUES(?,?,.265,?,?);SELECT CONVERT(INT,SCOPE_IDENTITY())', self.units[0], self.units[1], self.material, self.ctx.user_id).fetchval()
        self.migrate(); self.migrate()
        source = self.row(existing)
        self.assertEqual(source['Factor'], D('.265'))
        self.assertEqual(self.row(source['ReverseConversionID'])['Factor'], D('3.773584906'))
        self.assertEqual(self.cur.execute('SELECT COUNT(*) FROM dbo.UnitConversion WHERE RawMaterialID=?', self.material).fetchval(), 2)

    def test_migration_leaves_independent_conflicts_unchanged(self):
        for a, b, factor in ((self.units[0], self.units[1], 2), (self.units[1], self.units[0], 5)):
            self.cur.execute('INSERT dbo.UnitConversion(FromUoMID,ToUoMID,Factor,RawMaterialID,CreatedBy) VALUES(?,?,?,?,?)', a, b, factor, self.material, self.ctx.user_id)
        self.migrate()
        self.assertEqual([r[0] for r in self.cur.execute('SELECT Factor FROM dbo.UnitConversion WHERE RawMaterialID=? ORDER BY ID', self.material)], [D('2'), D('5')])
        self.assertEqual(self.cur.execute('SELECT COUNT(*) FROM dbo.UnitConversion WHERE RawMaterialID=? AND ReverseConversionID IS NOT NULL', self.material).fetchval(), 0)


if __name__ == '__main__': unittest.main()
