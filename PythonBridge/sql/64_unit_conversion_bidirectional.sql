-- After 63 (and 40). One maintained conversion creates a linked reciprocal.
-- Existing factors are preserved; conflicting independent pairs are not overwritten.
SET ANSI_NULLS ON;
SET QUOTED_IDENTIFIER ON;
SET XACT_ABORT OFF;
