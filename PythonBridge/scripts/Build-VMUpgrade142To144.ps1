# Mechanical bundle generation only; never connects to a database.
[CmdletBinding()]
param()
$ErrorActionPreference='Stop'
$taskRoot=Split-Path -Parent $PSScriptRoot
$taskOutput=Join-Path $taskRoot 'sql/deploy/upgrade_142_to_144_vm.sql'
$taskParts=@(@'
:on error exit
/*
PythonBridge VM upgrade 142-144. Requires the application database through 141.
Back up the database, stop the API and select the application database.
SSMS: enable SQLCMD Mode. sqlcmd: use -b -d YOUR_DATABASE -i this_file.sql.
The bundle is not atomic; migrations are rerunnable after correcting a failure.
Original Mix memberships and replaced procedures are archived; a full database
backup is still required. Existing pricing snapshots and quantities are retained.
Deploy matching core/ and webapp/dist/ before restarting. Keep LOCAL_AI_ENABLED=0.
Generated by scripts/Build-VMUpgrade142To144.ps1; do not edit embedded SQL.
*/
SET NOCOUNT ON;
SET XACT_ABORT ON;
SET ANSI_NULLS ON;
SET QUOTED_IDENTIFIER ON;
GO
IF DB_NAME() IN(N'master',N'model',N'msdb',N'tempdb') OR @@TRANCOUNT<>0
 THROW 52957,'Select the existing application database on a new connection.',1;
IF OBJECT_ID('dbo.GradeProcessLossMaster','U') IS NULL
 OR CHARINDEX(N'-- Nested grade processing (141)',COALESCE(OBJECT_DEFINITION(OBJECT_ID('dbo.usp_ProductGrade_Save')),N''))=0
 THROW 52957,'Apply migrations through 141 first.',1;
GO
'@)
foreach($taskName in @('142_pallet_material_max_payload.sql','143_four_packaging_layers.sql','144_packaging_reference_review.sql')){
 $taskText=Get-Content -LiteralPath (Join-Path $taskRoot ('sql/'+$taskName)) -Raw
 if($taskText -match '(?im)^\s*USE\s' -or $taskText -match '(?im)^\s*:'){
  throw "Unexpected database directive in $taskName"
 }
 $taskParts+=("-- SOURCE: "+$taskName+"`r`n"+$taskText+"`r`nGO")
}
$taskParts+=@'
IF COL_LENGTH('dbo.PackagingMaterial','MaxPayloadKG') IS NULL
 OR COL_LENGTH('dbo.PackagingConfigurationRequestItem','FourthPMType') IS NULL
 OR COL_LENGTH('dbo.PackagingConfigurationRequestItem','ReferenceSetupJSON') IS NULL
 OR OBJECT_ID('dbo.fn_PackagingResponseEditable','FN') IS NULL
 OR CHARINDEX('-- Global pricing references (144)',COALESCE(OBJECT_DEFINITION(OBJECT_ID('dbo.usp_PkgPricing_Save')),''))=0
 OR EXISTS(SELECT 1 FROM (VALUES
  ('usp_PackagingResponse_Batch_AuditImplementation'),
  ('usp_PackagingConfigurationRequestItem_Fields_Save_AuditImplementation'),
  ('usp_PkgPricing_ItemAuthorize')) p(Name)
  WHERE CHARINDEX('-- Reference review (144)',COALESCE(OBJECT_DEFINITION(OBJECT_ID('dbo.'+p.Name)),''))=0)
 THROW 52957,'Packaging upgrade 142-144 verification failed.',1;
IF @@TRANCOUNT<>0 THROW 52957,'Upgrade left an open transaction.',1;
PRINT N'Upgrade 142-144 verified. Deploy matching application files before restarting.';
GO
'@
Set-Content -LiteralPath $taskOutput -Value ($taskParts -join "`r`n") -Encoding UTF8
Write-Host "Generated $taskOutput"
