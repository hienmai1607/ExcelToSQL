# Mechanical bundle generation only; never connects to a database.
[CmdletBinding()]
param()
$ErrorActionPreference='Stop'
$taskRoot=Split-Path -Parent $PSScriptRoot
$taskNames=@('160_shipment_duty_breakdown.sql','161_shipment_duty_precision_payment_term.sql','162_opportunity_mix_version_refresh.sql','163_opportunity_item_delete_initial_tcb.sql')
$taskParts=@(@'
:on error exit
/* PythonBridge VM upgrade 160-163. Requires the database through 159.
Back up the database, stop the API, and select the existing application database.
Use SSMS SQLCMD mode or sqlcmd -b -d YOUR_DATABASE -i this_file.sql.
NOT atomic: original migration transaction boundaries are preserved. Rerunnable.
Only procedures and triggers change; no table data is modified.
Existing Duty % and Payment term (days) values stay valid and unchanged.
Saved Opportunity Mix items change only through an explicit user update.
Deleting a Draft item now also removes its automatic empty initial TCB version (163).
No QA cases, users or master data are deployed. Preserve VM environment settings.
Deploy matching core/, webapp/dist/ and templates/ before restarting.
Generated by scripts/Build-VMUpgrade160To163.ps1. Do not edit embedded SQL. */
SET NOCOUNT ON;
SET XACT_ABORT ON;
SET ANSI_NULLS ON;
SET QUOTED_IDENTIFIER ON;
GO
IF DB_NAME() IN(N'master',N'model',N'msdb',N'tempdb') OR @@TRANCOUNT<>0
 THROW 53059,'Select the existing application database on a new connection.',1;
IF (SELECT compatibility_level FROM sys.databases WHERE database_id=DB_ID())<130
 THROW 53059,'Database compatibility level 130 or newer is required.',1;
IF COL_LENGTH('dbo.NPDRecipeSheet','SalesReviewStatus') IS NULL
 OR CHARINDEX(N'-- Incoterms and WH breakdown (148)',COALESCE(OBJECT_DEFINITION(OBJECT_ID('dbo.usp_OpportunityShipment_Validate')),N''))=0
 THROW 53059,'Apply migrations through 159 first.',1;
GO
'@)
foreach($taskName in $taskNames){
 $taskText=Get-Content -LiteralPath (Join-Path $taskRoot ('sql/'+$taskName)) -Raw -Encoding UTF8
 if($taskText -match '(?im)^\s*(USE\s|:)'){throw "Unexpected database directive in $taskName"}
 $taskParts+=("-- BEGIN MIGRATION "+$taskName+"`r`nGO`r`n"+$taskText+"`r`nGO`r`n-- END MIGRATION "+$taskName)
}
$taskParts+=@'
-- VERIFY UPGRADE
DECLARE @V NVARCHAR(MAX)=COALESCE(OBJECT_DEFINITION(OBJECT_ID('dbo.usp_OpportunityShipment_Validate')),N'');
IF CHARINDEX(N'-- Duty breakdown (160)',@V)=0 OR CHARINDEX(N'''DutyBreakdown'',''WHCostBreakdown''',@V)=0
 THROW 53059,'Upgrade 160 Duty breakdown verification failed.',1;
IF CHARINDEX(N'-- Duty precision and payment term (161)',@V)=0 OR CHARINDEX(N'''PaymentTerm'',''DutyBreakdown''',@V)=0
 OR CHARINDEX(N'DECIMAL(19,4),JSON_VALUE(@Value,''$.DutyPct'')',@V)=0
 THROW 53059,'Upgrade 161 Duty precision and Payment term verification failed.',1;
IF OBJECT_ID('dbo.usp_OpportunityItem_MixRefresh','P') IS NULL
 OR CHARINDEX(N'OpportunityMixRefreshID',COALESCE(OBJECT_DEFINITION(OBJECT_ID('dbo.tr_OpportunityItem_MixDelete')),N''))=0
 OR CHARINDEX(N'OpportunityMixRefreshID',COALESCE(OBJECT_DEFINITION(OBJECT_ID('dbo.tr_OpportunityItem_MixChildren')),N''))=0
 THROW 53059,'Upgrade 162 Mix version update verification failed.',1;
IF CHARINDEX(N'-- Initial TCB version (163)',COALESCE(OBJECT_DEFINITION(OBJECT_ID('dbo.tr_OpportunityItem_MixDelete')),N''))=0
 THROW 53059,'Upgrade 163 item delete verification failed.',1;
IF @@TRANCOUNT<>0 THROW 53059,'Upgrade left an open transaction.',1;
PRINT N'Upgrade 160-163 verified. Deploy matching application files before restarting.';
GO
'@
Set-Content -LiteralPath (Join-Path $taskRoot 'sql/deploy/upgrade_160_to_163_vm.sql') -Value ($taskParts -join "`r`n") -Encoding UTF8
Write-Host 'Generated upgrade_160_to_163_vm.sql'
