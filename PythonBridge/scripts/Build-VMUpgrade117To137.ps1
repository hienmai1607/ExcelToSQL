# Mechanical concatenation only. Never connects to or modifies a database.
[CmdletBinding()]
param()
$ErrorActionPreference = 'Stop'
$taskRoot = Split-Path -Parent $PSScriptRoot
$taskSqlRoot = Join-Path $taskRoot 'sql'
$taskOutput = Join-Path $taskSqlRoot 'deploy/upgrade_117_to_137_vm.sql'
$taskSources = @(Get-ChildItem -LiteralPath $taskSqlRoot -Filter '*.sql' |
 Where-Object { $_.BaseName -match '^(\d+)_' -and [int]$Matches[1] -ge 117 -and [int]$Matches[1] -le 137 } |
 Sort-Object { [int]($_.BaseName.Split('_')[0]) })
if ($taskSources.Count -ne 21) { throw 'Expected exactly 21 migrations, 117 through 137.' }
$taskHeader = @'
:on error exit
/*
PythonBridge VM upgrade: migrations 117-137.
For an existing application database already through migration 116.
Back up the database and stop the API before executing.
SSMS: select the application database and enable Query > SQLCMD Mode.
sqlcmd -S YOUR_SERVER -d YOUR_DATABASE -E -b -i sql/deploy/upgrade_117_to_137_vm.sql
This upgrade is NOT atomic: source transaction boundaries are preserved.
Earlier migrations can remain committed if a later batch fails. Restore the backup to roll back.
No external includes, development USE directives, credentials or test data.
Migration 118 moves unambiguous physical measurements to Material; review flagged conflicts.
Migration 125 qualifies duplicate Packaging Type display names; IDs and references are preserved.
Migration 134 marks existing leaf raw grades Final; resolve materials linked to parents first.
Migration 136 captures current item TCB settings as Version 1; historical business records are retained.
Deploy matching core/, webapp/dist/ and templates from the same commit before restarting.
AI launcher is temporarily disabled; keep LOCAL_AI_ENABLED=0 on the VM.
Generated by scripts/Build-VMUpgrade117To137.ps1. Do not hand-edit embedded migrations.
*/
SET NOCOUNT ON;
SET XACT_ABORT ON;
SET ANSI_NULLS ON;
SET QUOTED_IDENTIFIER ON;
SET ANSI_PADDING ON;
SET ANSI_WARNINGS ON;
SET ARITHABORT ON;
SET CONCAT_NULL_YIELDS_NULL ON;
SET NUMERIC_ROUNDABORT OFF;
GO
IF DB_NAME() IN (N'master',N'model',N'msdb',N'tempdb')
 THROW 52957,'Select the existing application database, not a system database.',1;
IF @@TRANCOUNT<>0
 THROW 52957,'Run this upgrade on a new connection without an existing transaction.',1;
IF (SELECT compatibility_level FROM sys.databases WHERE database_id=DB_ID())<130
 THROW 52957,'Database compatibility level 130 or higher is required.',1;
IF OBJECT_ID('dbo.ResponseContainerLoadPlan','U') IS NULL
 OR OBJECT_ID('dbo.PalletPricingSnapshot','U') IS NULL
 OR OBJECT_ID('dbo.usp_PackagingPrice_BatchV6','P') IS NULL
 OR COL_LENGTH('dbo.OpportunityItem','TCBCostInfo') IS NULL
 OR COL_LENGTH('dbo.RawGrade','ParentGradeID') IS NULL
 OR COL_LENGTH('dbo.ProductGradeItem','RawMaterialID') IS NULL
 OR CHARINDEX(N'-- Independent container feedback (116)',COALESCE(OBJECT_DEFINITION(OBJECT_ID('dbo.usp_PackagingConfigurationRequestItem_Fields_Save_AuditImplementation')),N''))=0
 THROW 52957,'Apply migrations through 116 first; this is not a fresh database installer.',1;
PRINT N'Applying PythonBridge migrations 117-137 to '+QUOTENAME(DB_NAME());
GO
'@
$taskFooter = @'
-- VERIFY UPGRADE
IF @@TRANCOUNT<>0
 THROW 52957,'Upgrade left an open transaction. Stop and investigate.',1;
IF COL_LENGTH('dbo.PackagingMaterial','MaterialDimensionID') IS NULL
 OR COL_LENGTH('dbo.PackagingMaterial','MaterialDimensionsNeedsReview') IS NULL
 OR COL_LENGTH('dbo.PackagingConfigurationRequestItem','ResponsePalletMaterialID') IS NULL
 OR OBJECT_ID('dbo.BusinessDeletionAudit','U') IS NULL
 OR OBJECT_ID('dbo.LocalAIChatTurn','U') IS NULL
 OR COL_LENGTH('dbo.LocalAIChatTurn','Feedback') IS NULL
 OR OBJECT_ID('dbo.PackagingTypeParent','U') IS NULL
 OR COL_LENGTH('dbo.UoM','Category') IS NULL
 OR COL_LENGTH('dbo.UoM','BaseFactor') IS NULL
 OR COL_LENGTH('dbo.RawMaterial','Origin') IS NULL
 OR COL_LENGTH('dbo.RawGrade','FinalGrade') IS NULL
 OR OBJECT_ID('dbo.usp_OpportunityItem_RefreshProductWeight','P') IS NULL
 OR OBJECT_ID('dbo.usp_OpportunityItem_SetNetWeight','P') IS NULL
 OR OBJECT_ID('dbo.OpportunityTCBVersion','U') IS NULL
 OR OBJECT_ID('dbo.tr_OpportunityItem_TCBVersion','TR') IS NULL
 OR COL_LENGTH('dbo.ProductGradeItem','Process') IS NULL
 THROW 52957,'Upgrade verification failed: expected 117-137 schema objects are missing.',1;
IF NOT EXISTS(SELECT 1 FROM sys.indexes WHERE object_id=OBJECT_ID('dbo.OpportunityTCBVersion') AND name='UX_OpportunityTCBVersion_Active' AND is_unique=1 AND is_disabled=0 AND has_filter=1)
 OR NOT EXISTS(SELECT 1 FROM sys.indexes WHERE object_id=OBJECT_ID('dbo.PackagingType') AND name='UX_PackagingType_GlobalName' AND is_unique=1 AND is_disabled=0)
 OR NOT EXISTS(SELECT 1 FROM sys.parameters WHERE object_id=OBJECT_ID('dbo.usp_PackagingPrice_BatchV5') AND name='@ResolveOverlap')
 OR CHARINDEX(N'GradeProcess137',COALESCE(OBJECT_DEFINITION(OBJECT_ID('dbo.usp_ProductGrade_Save')),N''))=0
 THROW 52957,'Upgrade verification failed: pricing, Process recipe or active-version contracts are missing.',1;
PRINT N'PythonBridge upgrade 117-137 verified. Deploy matching application files before restarting.';
PRINT N'Review MaterialDimensionsNeedsReview flags, Packaging Type names and Final grade assignments.';
PRINT N'AI remains disabled for VM rollout. Preserve VM-local secrets, uploads and service configuration.';
GO
'@
$taskBundle = [Text.StringBuilder]::new()
[void]$taskBundle.AppendLine($taskHeader.TrimEnd())
foreach ($taskSource in $taskSources) {
 $taskBody = [IO.File]::ReadAllText($taskSource.FullName).Replace([string][char]13, '')
 if ($taskBody -match '(?im)^\s*(USE\s|:r\s)') { throw "Unexpected target/include directive: $($taskSource.Name)" }
 [void]$taskBundle.AppendLine("-- BEGIN MIGRATION $($taskSource.Name)")
 [void]$taskBundle.AppendLine("PRINT N'Applying $($taskSource.Name)';")
 [void]$taskBundle.AppendLine('GO')
 [void]$taskBundle.AppendLine($taskBody.TrimEnd())
 [void]$taskBundle.AppendLine('GO')
 [void]$taskBundle.AppendLine("-- END MIGRATION $($taskSource.Name)")
 [void]$taskBundle.AppendLine('GO')
}
[void]$taskBundle.AppendLine($taskFooter.TrimEnd())
$taskText = $taskBundle.ToString().Replace([string][char]13, '')
[IO.File]::WriteAllText($taskOutput, $taskText, [Text.UTF8Encoding]::new($false))
Write-Output "Generated $taskOutput ($($taskSources.Count) migrations)."
