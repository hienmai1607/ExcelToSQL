[CmdletBinding()]
param()
$ErrorActionPreference='Stop'
$taskRoot=Split-Path -Parent $PSScriptRoot
$taskNames=@('142_pallet_material_max_payload.sql','143_four_packaging_layers.sql','144_packaging_reference_review.sql','145_optional_shipping_d2.sql','146_container_proposal_flags.sql','147_required_container_proposal.sql')
$taskParts=@(@'
:on error exit
/* PythonBridge VM upgrade 142-147. Requires the database through 141.
Back up the database, stop the API, and select the application database.
Use SSMS SQLCMD mode or sqlcmd -b -d YOUR_DATABASE -i this_file.sql.
NOT atomic: original migration transaction boundaries are preserved.
Migrations are rerunnable. Original memberships and procedures are archived;
historical quantities, prices and snapshots are retained. Only approved legacy
Mix memberships are retired and the two approved pallet defaults are initialized.
Deploy matching core/ and webapp/dist/ before restarting. Keep LOCAL_AI_ENABLED=0.
Generated by scripts/Build-VMUpgrade142To147.ps1. Do not edit embedded SQL. */
SET NOCOUNT ON;
SET XACT_ABORT ON;
SET ANSI_NULLS ON;
SET QUOTED_IDENTIFIER ON;
GO
IF DB_NAME() IN(N'master',N'model',N'msdb',N'tempdb') OR @@TRANCOUNT<>0
 THROW 52957,'Select the existing application database on a new connection.',1;
IF (SELECT compatibility_level FROM sys.databases WHERE database_id=DB_ID())<130
 THROW 52957,'Database compatibility level 130 or newer is required.',1;
IF OBJECT_ID('dbo.GradeProcessLossMaster','U') IS NULL
 OR CHARINDEX(N'-- Nested grade processing (141)',COALESCE(OBJECT_DEFINITION(OBJECT_ID('dbo.usp_ProductGrade_Save')),N''))=0
 THROW 52957,'Apply migrations through 141 first.',1;
GO
'@)
foreach($taskName in $taskNames){
 $taskText=Get-Content -LiteralPath (Join-Path $taskRoot ('sql/'+$taskName)) -Raw -Encoding UTF8
 if($taskText -match '(?im)^\s*(USE\s|:)'){throw "Unexpected database directive in $taskName"}
 $taskParts+=("-- BEGIN MIGRATION "+$taskName+"`r`nGO`r`n"+$taskText+"`r`nGO`r`n-- END MIGRATION "+$taskName)
}
$taskParts+=@'
-- VERIFY UPGRADE
IF COL_LENGTH('dbo.PackagingMaterial','MaxPayloadKG') IS NULL
 OR COL_LENGTH('dbo.PackagingConfigurationRequestItem','FourthPMType') IS NULL
 OR COL_LENGTH('dbo.OpportunityItem','QuaternaryTypeID') IS NULL
 OR COL_LENGTH('dbo.PackagingConfigurationRequestItem','ReferenceSetupJSON') IS NULL
 OR OBJECT_ID('dbo.PackagingLayerMigrationArchive','U') IS NULL
 OR OBJECT_ID('dbo.fn_PackagingResponseEditable','FN') IS NULL
 OR OBJECT_ID('dbo.fn_RequestRequestedPackagingLayerStart','FN') IS NULL
 THROW 52957,'Upgrade 142-147 required columns or functions are missing.',1;
GO
IF dbo.fn_PackagingGlobalOrder('Primary',4)<>'Quaternary'
 OR EXISTS(SELECT 1 FROM dbo.PackagingTypeOrder WHERE PackagingOrder IN(N'Primary Mix',N'Secondary Mix',N'Tertiary Mix'))
 THROW 52957,'Upgrade 143 layer mapping verification failed.',1;
IF EXISTS(SELECT 1 FROM (VALUES
 ('usp_PackagingDimension_Save'),('usp_PackagingDimension_SaveV2'),
 ('tr_PackagingDimension_ParentGeometry'),('tr_PackagingType_ShippingDimensions'),
 ('tr_PackagingDimension_ShippingRequired')) d(Name)
 WHERE CHARINDEX('-- Optional shipping D2 (145)',COALESCE(OBJECT_DEFINITION(OBJECT_ID('dbo.'+d.Name)),''))=0)
 OR CHARINDEX('-- Global pricing references (144)',COALESCE(OBJECT_DEFINITION(OBJECT_ID('dbo.usp_PkgPricing_Save')),''))=0
 OR EXISTS(SELECT 1 FROM (VALUES
 ('usp_PackagingResponse_Batch_AuditImplementation'),
 ('usp_PackagingConfigurationRequestItem_Fields_Save_AuditImplementation'),
 ('usp_PkgPricing_ItemAuthorize')) p(Name)
 WHERE CHARINDEX('-- Reference review (144)',COALESCE(OBJECT_DEFINITION(OBJECT_ID('dbo.'+p.Name)),''))=0)
 THROW 52957,'Upgrade 144-145 procedure verification failed.',1;
IF CHARINDEX('-- Container proposal flags (146)',COALESCE(OBJECT_DEFINITION(OBJECT_ID('dbo.usp_PackagingConfigurationRequestItem_Fields_Save_AuditImplementation')),''))=0
 OR CHARINDEX('-- Required container proposal (147)',COALESCE(OBJECT_DEFINITION(OBJECT_ID('dbo.usp_PackagingConfigurationRequestItem_Fields_Save_AuditImplementation')),''))=0
 THROW 52957,'Upgrade 146-147 proposal verification failed.',1;
IF @@TRANCOUNT<>0 THROW 52957,'Upgrade left an open transaction.',1;
PRINT N'Upgrade 142-147 verified. Deploy matching application files before restarting.';
GO
'@
Set-Content -LiteralPath (Join-Path $taskRoot 'sql/deploy/upgrade_142_to_147_vm.sql') -Value ($taskParts -join "`r`n") -Encoding UTF8
Write-Host 'Generated upgrade_142_to_147_vm.sql'
