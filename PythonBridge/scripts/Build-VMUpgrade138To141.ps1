# Mechanical concatenation only. Never connects to or modifies a database.
[CmdletBinding()]
param()
$ErrorActionPreference = 'Stop'
$taskRoot = Split-Path -Parent $PSScriptRoot
$taskSqlRoot = Join-Path $taskRoot 'sql'
$taskOutput = Join-Path $taskSqlRoot 'deploy/upgrade_138_to_141_vm.sql'
$taskSources = @(Get-ChildItem -LiteralPath $taskSqlRoot -Filter '*.sql' |
 Where-Object { $_.BaseName -match '^(\d+)_' -and [int]$Matches[1] -ge 138 -and [int]$Matches[1] -le 141 } |
 Sort-Object { [int]($_.BaseName.Split('_')[0]) })
if ($taskSources.Count -ne 4) { throw 'Expected exactly four migrations, 138 through 141.' }
$taskHeader = @'
:on error exit
/*
PythonBridge VM upgrade: migrations 138-141.
For an existing application database already through migration 137.
Back up the database and stop the API before executing.
SSMS: select the application database and enable Query > SQLCMD Mode.
sqlcmd -S YOUR_SERVER -d YOUR_DATABASE -E -b -i sql/deploy/upgrade_138_to_141_vm.sql
This upgrade is NOT atomic: source transaction boundaries are preserved.
Earlier migrations can remain committed if a later batch fails. Restore the backup to roll back.
Rerunnable, including when migration 138 was previously applied.
Existing master values, captured grade trees, TCB settings and historical records are retained.
No external includes, development USE directives, credentials or test data.
Deploy matching core/ and webapp/dist/ from the same commit before restarting.
Keep LOCAL_AI_ENABLED=0 and preserve VM-local secrets, uploads and service configuration.
Generated by scripts/Build-VMUpgrade138To141.ps1. Do not hand-edit embedded migrations.
*/
SET NOCOUNT ON;
SET XACT_ABORT ON;
SET ANSI_NULLS ON;
SET QUOTED_IDENTIFIER ON;
SET ANSI_PADDING ON;
SET ANSI_WARNINGS ON;
SET ARITHABORT ON;
SET CONCAT_NULL_YIELDS_NULL ON;
SET NUMERIC_ROUNDABORT OFF;
GO
IF DB_NAME() IN (N'master',N'model',N'msdb',N'tempdb')
 THROW 52957,'Select the existing application database, not a system database.',1;
IF @@TRANCOUNT<>0
 THROW 52957,'Run this upgrade on a new connection without an existing transaction.',1;
IF (SELECT compatibility_level FROM sys.databases WHERE database_id=DB_ID())<130
 THROW 52957,'Database compatibility level 130 or higher is required.',1;
IF OBJECT_ID('dbo.OpportunityTCBVersion','U') IS NULL
 OR OBJECT_ID('dbo.LossProcessMaster','U') IS NULL
 OR OBJECT_ID('dbo.fn_WorkspaceAccess','FN') IS NULL
 OR COL_LENGTH('dbo.ProductGradeItem','Process') IS NULL
 OR CHARINDEX(N'GradeProcess137',COALESCE(OBJECT_DEFINITION(OBJECT_ID('dbo.usp_ProductGrade_Save')),N''))=0
 OR CHARINDEX(N'ImportClearanceCustomerPerContainer',COALESCE(OBJECT_DEFINITION(OBJECT_ID('dbo.usp_OpportunityShipment_Validate')),N''))=0
 THROW 52957,'Apply migrations through 137 first; this is not a fresh database installer.',1;
PRINT N'Applying PythonBridge migrations 138-141 to '+QUOTENAME(DB_NAME());
GO
'@
$taskFooter = @'
-- VERIFY UPGRADE
IF @@TRANCOUNT<>0
 THROW 52957,'Upgrade left an open transaction. Stop and investigate.',1;
IF COL_LENGTH('dbo.LossProcessMaster','Shared') IS NULL
 OR OBJECT_ID('dbo.GradeProcessLossMaster','U') IS NULL
 OR OBJECT_ID('dbo.usp_GradeProcessLoss_Save','P') IS NULL
 OR NOT EXISTS(SELECT 1 FROM sys.parameters WHERE object_id=OBJECT_ID('dbo.usp_LossProcessMaster_Save') AND name='@Shared')
 OR CHARINDEX(N'-- Shipment customer currency (138)',COALESCE(OBJECT_DEFINITION(OBJECT_ID('dbo.usp_OpportunityShipment_Validate')),N''))=0
 OR CHARINDEX(N'-- Mix child Others ownership (140)',COALESCE(OBJECT_DEFINITION(OBJECT_ID('dbo.usp_OpportunityShipment_Validate')),N''))=0
 OR CHARINDEX(N'-- Mix child Others save (140)',COALESCE(OBJECT_DEFINITION(OBJECT_ID('dbo.usp_OpportunityItem_Fields_Save')),N''))=0
 OR CHARINDEX(N'-- Nested grade processing (141)',COALESCE(OBJECT_DEFINITION(OBJECT_ID('dbo.usp_ProductGrade_Save')),N''))=0
 THROW 52957,'Upgrade verification failed: expected 138-141 schema or procedure contracts are missing.',1;
IF NOT EXISTS(SELECT 1 FROM sys.indexes WHERE object_id=OBJECT_ID('dbo.GradeProcessLossMaster') AND name='UX_GradeProcessLoss_Grade' AND is_unique=1 AND is_disabled=0 AND has_filter=1)
 OR NOT EXISTS(SELECT 1 FROM sys.indexes WHERE object_id=OBJECT_ID('dbo.GradeProcessLossMaster') AND name='UX_GradeProcessLoss_All' AND is_unique=1 AND is_disabled=0 AND has_filter=1)
 THROW 52957,'Upgrade verification failed: Grade and All grades default uniqueness is missing.',1;
PRINT N'PythonBridge upgrade 138-141 verified. Deploy matching application files before restarting.';
PRINT N'Existing Mix parent Others amounts were not moved to children. Review child-specific costs explicitly.';
PRINT N'Saved loading plans remain snapshots; explicitly recalculate affected Mix plans if required.';
GO
'@
$taskBundle = [Text.StringBuilder]::new()
[void]$taskBundle.AppendLine($taskHeader.TrimEnd())
foreach ($taskSource in $taskSources) {
 $taskBody = [IO.File]::ReadAllText($taskSource.FullName).Replace([string][char]13, '')
 if ($taskBody -match '(?im)^\s*(USE\s|:r\s)') { throw "Unexpected target/include directive: $($taskSource.Name)" }
 [void]$taskBundle.AppendLine("-- BEGIN MIGRATION $($taskSource.Name)")
 [void]$taskBundle.AppendLine("PRINT N'Applying $($taskSource.Name)';")
 [void]$taskBundle.AppendLine('GO')
 [void]$taskBundle.AppendLine($taskBody.TrimEnd())
 [void]$taskBundle.AppendLine('GO')
 [void]$taskBundle.AppendLine("-- END MIGRATION $($taskSource.Name)")
 [void]$taskBundle.AppendLine('GO')
}
[void]$taskBundle.AppendLine($taskFooter.TrimEnd())
[IO.File]::WriteAllText($taskOutput, $taskBundle.ToString().Replace([string][char]13, ''), [Text.UTF8Encoding]::new($false))
Write-Output "Generated $taskOutput ($($taskSources.Count) migrations)."
