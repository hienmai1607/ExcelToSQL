# Mechanical bundle generation only; never connects to a database.
[CmdletBinding()]
param()
$ErrorActionPreference='Stop'
$taskRoot=Split-Path -Parent $PSScriptRoot
$taskNames=@('148_shipment_incoterms_warehouse_cost.sql','149_approved_packaging_feedback.sql','150_material_tare_mass_units.sql','151_unpriced_pallet_material_choices.sql')
$taskParts=@(@'
:on error exit
/* PythonBridge VM upgrade 148-151. Requires the database through 147.
Back up the database, stop the API, and select the existing application database.
Use SSMS SQLCMD mode or sqlcmd -b -d YOUR_DATABASE -i this_file.sql.
NOT atomic: original migration transaction boundaries are preserved.
Migrations are rerunnable; existing business rows and snapshots are unchanged.
Deploy matching core/ and webapp/dist/ before restarting. Keep LOCAL_AI_ENABLED=0.
Generated by scripts/Build-VMUpgrade148To151.ps1. Do not edit embedded SQL. */
SET NOCOUNT ON;
SET XACT_ABORT ON;
SET ANSI_NULLS ON;
SET QUOTED_IDENTIFIER ON;
GO
IF DB_NAME() IN(N'master',N'model',N'msdb',N'tempdb') OR @@TRANCOUNT<>0
 THROW 52957,'Select the existing application database on a new connection.',1;
IF (SELECT compatibility_level FROM sys.databases WHERE database_id=DB_ID())<130
 THROW 52957,'Database compatibility level 130 or newer is required.',1;
IF CHARINDEX(N'-- Required container proposal (147)',COALESCE(OBJECT_DEFINITION(OBJECT_ID('dbo.usp_PackagingConfigurationRequestItem_Fields_Save_AuditImplementation')),N''))=0
 THROW 52957,'Apply migrations through 147 first.',1;
GO
'@)
foreach($taskName in $taskNames){
 $taskText=Get-Content -LiteralPath (Join-Path $taskRoot ('sql/'+$taskName)) -Raw -Encoding UTF8
 if($taskText -match '(?im)^\s*(USE\s|:)'){throw "Unexpected database directive in $taskName"}
 $taskParts+=("-- BEGIN MIGRATION "+$taskName+"`r`nGO`r`n"+$taskText+"`r`nGO`r`n-- END MIGRATION "+$taskName)
}
$taskParts+=@'
-- VERIFY UPGRADE
IF CHARINDEX(N'-- Incoterms and WH breakdown (148)',COALESCE(OBJECT_DEFINITION(OBJECT_ID('dbo.usp_OpportunityShipment_Validate')),N''))=0
 OR CHARINDEX(N'-- Approved packaging feedback (149)',COALESCE(OBJECT_DEFINITION(OBJECT_ID('dbo.v_OpportunityItemPackaging')),N''))=0
 THROW 52957,'Upgrade 148-149 procedure or publication verification failed.',1;
IF NOT EXISTS(SELECT 1 FROM sys.check_constraints WHERE parent_object_id=OBJECT_ID('dbo.PackagingMaterial')
 AND name=N'CK_PackagingMaterial_TareMassUnit' AND is_disabled=0 AND is_not_trusted=0)
 THROW 52957,'Upgrade 150 tare-unit constraint verification failed.',1;
IF CHARINDEX(N'-- Material availability independent of pricing (151)',COALESCE(OBJECT_DEFINITION(OBJECT_ID('dbo.v_PalletSizeChoice')),N''))=0
 OR CHARINDEX(N'dbo.PackagingPrice',COALESCE(OBJECT_DEFINITION(OBJECT_ID('dbo.v_PalletSizeChoice')),N''))>0
 THROW 52957,'Upgrade 151 material-only pallet lookup verification failed.',1;
IF @@TRANCOUNT<>0 THROW 52957,'Upgrade left an open transaction.',1;
PRINT N'Upgrade 148-151 verified. Deploy matching application files before restarting.';
GO
'@
Set-Content -LiteralPath (Join-Path $taskRoot 'sql/deploy/upgrade_148_to_151_vm.sql') -Value ($taskParts -join "`r`n") -Encoding UTF8
Write-Host 'Generated upgrade_148_to_151_vm.sql'
