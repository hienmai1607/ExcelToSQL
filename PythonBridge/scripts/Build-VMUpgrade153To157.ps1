# Mechanical bundle generation only; never connects to a database.
[CmdletBinding()]
param()
$ErrorActionPreference='Stop'
$taskRoot=Split-Path -Parent $PSScriptRoot
$taskNames=@('153_pallet_requirement_comments.sql','154_npd_recipes.sql','155_recipe_components.sql','156_recipe_sheet_buffered_pricing.sql','157_ingredient_grade_nature.sql')
$taskParts=@(@'
:on error exit
/* PythonBridge VM upgrade 153-157. Requires the database through 152.
Back up the database, stop the API, and select the existing application database.
Use SSMS SQLCMD mode or sqlcmd -b -d YOUR_DATABASE -i this_file.sql.
NOT atomic: original migration transaction boundaries are preserved.
Rerunnable. Seeds NPD roles, access defaults, Recipe Components and Seasoning.
Backfills missing recipe-confirmation metadata; existing approved calculations remain.
No desktop QA cases, users, ingredient prices or SharePoint integration are deployed.
Deploy matching core/ and webapp/dist/ before restarting. Preserve VM environment.
Generated by scripts/Build-VMUpgrade153To157.ps1. Do not edit embedded SQL. */
SET NOCOUNT ON;
SET XACT_ABORT ON;
SET ANSI_NULLS ON;
SET QUOTED_IDENTIFIER ON;
GO
IF DB_NAME() IN(N'master',N'model',N'msdb',N'tempdb') OR @@TRANCOUNT<>0
 THROW 53057,'Select the existing application database on a new connection.',1;
IF (SELECT compatibility_level FROM sys.databases WHERE database_id=DB_ID())<130
 THROW 53057,'Database compatibility level 130 or newer is required.',1;
IF OBJECT_ID('dbo.OpportunityTCBVersion','U') IS NULL
 OR CHARINDEX(N'-- Quaternary TCB loss assignments (152)',COALESCE(OBJECT_DEFINITION(OBJECT_ID('dbo.usp_OpportunityTCB_Save')),N''))=0
 THROW 53057,'Apply migrations through 152 first.',1;
GO
'@)
foreach($taskName in $taskNames){
 $taskText=Get-Content -LiteralPath (Join-Path $taskRoot ('sql/'+$taskName)) -Raw -Encoding UTF8
 if($taskText -match '(?im)^\s*(USE\s|:)'){throw "Unexpected database directive in $taskName"}
 $taskParts+=("-- BEGIN MIGRATION "+$taskName+"`r`nGO`r`n"+$taskText+"`r`nGO`r`n-- END MIGRATION "+$taskName)
}
$taskParts+=@'
-- VERIFY UPGRADE
IF COL_LENGTH('dbo.OpportunityItem','PalletSpecialComments') IS NULL
 OR COL_LENGTH('dbo.PackagingConfigurationRequestItem','PalletSpecialComments') IS NULL
 OR CHARINDEX(N'PalletSpecialComments',COALESCE(OBJECT_DEFINITION(OBJECT_ID('dbo.usp_PackagingRequest_Create_AuditImplementation')),N''))=0
 THROW 53057,'Upgrade 153 pallet comments verification failed.',1;
IF OBJECT_ID('dbo.NPDIngredient','U') IS NULL OR OBJECT_ID('dbo.NPDIngredientPrice','U') IS NULL
 OR OBJECT_ID('dbo.NPDRecipeRequest','U') IS NULL OR OBJECT_ID('dbo.NPDRecipeRequestItem','U') IS NULL
 OR OBJECT_ID('dbo.NPDRecipeSheet','U') IS NULL OR OBJECT_ID('dbo.NPDAudit','U') IS NULL
 OR NOT EXISTS(SELECT 1 FROM dbo.WorkspaceRole WHERE RoleName='NPD Member')
 OR NOT EXISTS(SELECT 1 FROM dbo.WorkspaceRole WHERE RoleName='NPD Manager')
 THROW 53057,'Upgrade 154 NPD schema and roles verification failed.',1;
IF OBJECT_ID('dbo.ProcessRecipeComponent','U') IS NULL
 OR COL_LENGTH('dbo.ProductGradeVersion','RequiresRecipeConfirmation') IS NULL
 OR COL_LENGTH('dbo.NPDRecipeRequestItem','IsLinked') IS NULL
 OR (SELECT COUNT(*) FROM dbo.RecipeComponent WHERE SystemKey IN('Salt','Oil','Seasoning'))<>3
 OR OBJECT_ID('dbo.tr_OpportunityItem_RecipeLock','TR') IS NULL
 OR OBJECT_ID('dbo.tr_OpportunityItem_RecipeDefaults','TR') IS NULL
 OR EXISTS(SELECT 1 FROM sys.triggers WHERE object_id IN(OBJECT_ID('dbo.tr_OpportunityItem_RecipeLock'),OBJECT_ID('dbo.tr_OpportunityItem_RecipeDefaults')) AND is_disabled=1)
 THROW 53057,'Upgrade 155 recipe configuration and locks verification failed.',1;
IF COL_LENGTH('dbo.NPDRecipeSheet','ExchangeRateVNDPerUSD') IS NULL
 OR NOT EXISTS(SELECT 1 FROM sys.columns WHERE object_id=OBJECT_ID('dbo.NPDRecipeSheet') AND name='SeasoningLossPct' AND precision=28 AND scale=12)
 OR NOT EXISTS(SELECT 1 FROM sys.check_constraints WHERE parent_object_id=OBJECT_ID('dbo.NPDRecipeSheet') AND name='CK_NPDRecipeSheet_SeasoningLoss' AND is_disabled=0 AND is_not_trusted=0)
 THROW 53057,'Upgrade 156 sheet FX and buffered pricing verification failed.',1;
IF COL_LENGTH('dbo.NPDIngredient','GradeNature') IS NULL
 THROW 53057,'Upgrade 157 ingredient grade metadata verification failed.',1;
IF @@TRANCOUNT<>0 THROW 53057,'Upgrade left an open transaction.',1;
PRINT N'Upgrade 153-157 verified. Deploy matching application files before restarting.';
GO
'@
Set-Content -LiteralPath (Join-Path $taskRoot 'sql/deploy/upgrade_153_to_157_vm.sql') -Value ($taskParts -join "`r`n") -Encoding UTF8
Write-Host 'Generated upgrade_153_to_157_vm.sql'
