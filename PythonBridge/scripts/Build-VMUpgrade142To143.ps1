# Mechanical release artifact generation only; does not connect to SQL Server.
[CmdletBinding()]
param()
$ErrorActionPreference='Stop'
$taskRoot=Split-Path -Parent $PSScriptRoot
$taskSources=@('142_pallet_material_max_payload.sql','143_four_packaging_layers.sql')
$taskOutput=Join-Path $taskRoot 'sql/deploy/upgrade_142_to_143_vm.sql'
$taskHeader=@'
:on error exit
/*
PythonBridge VM upgrade 142-143. Requires the existing database through 141.
Back up the database, stop the API and select the application database.
SSMS: enable Query > SQLCMD Mode. sqlcmd: use -b -d YOUR_DATABASE -i this_file.sql.
Not atomic: 142 can remain committed if 143 fails. Both migrations are rerunnable.
143 archives original Mix memberships and procedure definitions before replacing them.
Existing prices, component quantities and historical pricing snapshots are retained.
An existing family over four layers stops migration; no layer is silently removed.
Deploy matching core/ and webapp/dist/ before restarting. Keep LOCAL_AI_ENABLED=0.
Generated by scripts/Build-VMUpgrade142To143.ps1; do not hand-edit embedded SQL.
*/
SET NOCOUNT ON;
SET XACT_ABORT ON;
SET ANSI_NULLS ON;
SET QUOTED_IDENTIFIER ON;
GO
IF DB_NAME() IN(N'master',N'model',N'msdb',N'tempdb') OR @@TRANCOUNT<>0
 THROW 52957,'Select the existing application database on a new connection.',1;
IF OBJECT_ID('dbo.GradeProcessLossMaster','U') IS NULL
 OR CHARINDEX(N'-- Nested grade processing (141)',COALESCE(OBJECT_DEFINITION(OBJECT_ID('dbo.usp_ProductGrade_Save')),N''))=0
 THROW 52957,'Apply migrations through 141 first.',1;
GO
'@
$taskParts=@($taskHeader)
foreach($taskName in $taskSources){
 $taskPath=Join-Path $taskRoot ('sql/'+$taskName)
 $taskText=Get-Content -LiteralPath $taskPath -Raw
 if($taskText -match '(?im)^\s*USE\s' -or $taskText -match '(?im)^\s*:'){
  throw "Unexpected database directive in $taskName"
 }
 $taskParts+=("-- SOURCE: "+$taskName+"`r`n"+$taskText+"`r`nGO")
}
$taskParts+=@'
IF COL_LENGTH('dbo.PackagingMaterial','MaxPayloadKG') IS NULL
 OR COL_LENGTH('dbo.PackagingConfigurationRequestItem','FourthPMType') IS NULL
 OR COL_LENGTH('dbo.OpportunityItem','QuaternaryTypeID') IS NULL
 OR OBJECT_ID('dbo.PackagingLayerMigrationArchive','U') IS NULL
 OR OBJECT_ID('dbo.fn_RequestPackagingLayerStart','FN') IS NULL
 OR OBJECT_ID('dbo.fn_RequestRequestedPackagingLayerStart','FN') IS NULL
 OR OBJECT_ID('dbo.usp_PackagingLayers_Validate','P') IS NULL
 THROW 52957,'Four-layer upgrade verification failed.',1;
IF @@TRANCOUNT<>0 THROW 52957,'Upgrade left an open transaction.',1;
PRINT N'Upgrade 142-143 verified. Deploy matching application files before restarting.';
GO
'@
Set-Content -LiteralPath $taskOutput -Value ($taskParts -join "`r`n") -Encoding UTF8
Write-Host "Generated $taskOutput"
