# Mechanical bundle generation only; never connects to a database.
[CmdletBinding()]
param()
$ErrorActionPreference='Stop'
$taskRoot=Split-Path -Parent $PSScriptRoot
$taskNames=@('158_opportunity_estimate_delivery_date.sql','159_sales_response_review.sql')
$taskParts=@(@'
:on error exit
/* PythonBridge VM upgrade 158-159. Requires the database through 157.
Back up the database, stop the API, and select the existing application database.
Use SSMS SQLCMD mode or sqlcmd -b -d YOUR_DATABASE -i this_file.sql.
NOT atomic: original migration transaction boundaries are preserved. Rerunnable.
Existing published manager-approved recipes become Sales accepted once; published
packaging results remain unchanged. Conflicting legacy delivery dates stay blank.
No QA cases, users or master data are deployed. Preserve VM environment settings.
Deploy matching core/ and webapp/dist/ before restarting.
Generated by scripts/Build-VMUpgrade158To159.ps1. Do not edit embedded SQL. */
SET NOCOUNT ON;
SET XACT_ABORT ON;
SET ANSI_NULLS ON;
SET QUOTED_IDENTIFIER ON;
GO
IF DB_NAME() IN(N'master',N'model',N'msdb',N'tempdb') OR @@TRANCOUNT<>0
 THROW 53059,'Select the existing application database on a new connection.',1;
IF (SELECT compatibility_level FROM sys.databases WHERE database_id=DB_ID())<130
 THROW 53059,'Database compatibility level 130 or newer is required.',1;
IF COL_LENGTH('dbo.NPDIngredient','GradeNature') IS NULL
 OR COL_LENGTH('dbo.NPDRecipeSheet','ExchangeRateVNDPerUSD') IS NULL
 OR OBJECT_ID('dbo.tr_OpportunityItem_RecipeLock','TR') IS NULL
 THROW 53059,'Apply migrations through 157 first.',1;
GO
'@)
foreach($taskName in $taskNames){
 $taskText=Get-Content -LiteralPath (Join-Path $taskRoot ('sql/'+$taskName)) -Raw -Encoding UTF8
 if($taskText -match '(?im)^\s*(USE\s|:)'){throw "Unexpected database directive in $taskName"}
 $taskParts+=("-- BEGIN MIGRATION "+$taskName+"`r`nGO`r`n"+$taskText+"`r`nGO`r`n-- END MIGRATION "+$taskName)
}
$taskParts+=@'
-- VERIFY UPGRADE
IF COL_LENGTH('dbo.Opportunity','EstimateDeliveryDate') IS NULL
 OR CHARINDEX(N'EstimateDeliveryDate',COALESCE(OBJECT_DEFINITION(OBJECT_ID('dbo.usp_Opportunity_Fields_Save')),N''))=0
 OR CHARINDEX(N'EstimateDeliveryDate',COALESCE(OBJECT_DEFINITION(OBJECT_ID('dbo.tr_Opportunity_ChangeLog')),N''))=0
 THROW 53059,'Upgrade 158 delivery date verification failed.',1;
IF COL_LENGTH('dbo.PackagingConfigurationRequestItem','SalesReviewedAt') IS NULL
 OR COL_LENGTH('dbo.NPDRecipeSheet','SalesReviewStatus') IS NULL
 OR CHARINDEX(N'Awaiting Sales',COALESCE(OBJECT_DEFINITION(OBJECT_ID('dbo.usp_PackagingRequestItem_Transition_AuditImplementation')),N''))=0
 OR NOT EXISTS(SELECT 1 FROM sys.check_constraints WHERE name='CK_NPD_SalesReviewStatus' AND is_disabled=0 AND is_not_trusted=0)
 OR NOT EXISTS(SELECT 1 FROM sys.check_constraints WHERE name='CK_PCRI_Open' AND is_disabled=0 AND is_not_trusted=0)
 OR NOT EXISTS(SELECT 1 FROM sys.check_constraints WHERE name='CK_PCRI_Stage' AND is_disabled=0 AND is_not_trusted=0)
 THROW 53059,'Upgrade 159 Sales review verification failed.',1;
IF @@TRANCOUNT<>0 THROW 53059,'Upgrade left an open transaction.',1;
PRINT N'Upgrade 158-159 verified. Deploy matching application files before restarting.';
GO
'@
Set-Content -LiteralPath (Join-Path $taskRoot 'sql/deploy/upgrade_158_to_159_vm.sql') -Value ($taskParts -join "`r`n") -Encoding UTF8
Write-Host 'Generated upgrade_158_to_159_vm.sql'
